def limits(name, cat):
    if name in LIMITS_BY_NAME:
        return LIMITS_BY_NAME[name]
    if name in NUTS:
        return (15, 40, 5)
    if name in READY_DISHES or name in DISH_TAGS:
        return LIMITS_BY_CAT["dishes"]
    return LIMITS_BY_CAT.get(cat, (40, 300, 10))


def tags(food):
    name, cat = food[0], food[5]
    t = set(DISH_TAGS.get(name, set()))
    if cat in ("meat", "fish", "dairy"):
        t.add(cat)
    return t


def plan_meal(template, budget, food_map):
    """Граммы каждого продукта: доля калорий → граммы, с учётом границ порции.
    Недобор калорий из-за границ переносится на продукты, у которых есть запас."""
    items = [(food_map[n], share) for n, share in template if n in food_map and share > 0]
    if not items:
        return []
    total_share = sum(s for _, s in items)
    plan = []  # [продукт, граммы, мин, макс, шаг, доля]
    for f, share in items:
        lo, hi, step = limits(f[0], f[5])
        g = budget * share / total_share / f[1] * 100 if f[1] > 0 else lo
        plan.append([f, min(hi, max(lo, g)), lo, hi, step, share])
    for _ in range(4):  # перераспределяем недобор/перебор калорий между продуктами с запасом
        missing = budget - sum(p[0][1] * p[1] / 100 for p in plan)
        if abs(missing) < budget * 0.03:
            break
        room = [p for p in plan if p[0][1] > 0 and (p[1] < p[3] if missing > 0 else p[1] > p[2])]
        main = [p for p in room if p[0][5] not in ("veg", "fruit")]
        room = main or room  # калории добираем основными продуктами, а не огурцами
        if not room:
            break
        shares = sum(p[5] for p in room)
        for p in room:
            p[1] = min(p[3], max(p[2], p[1] + missing * p[5] / shares / p[0][1] * 100))
    out = []
    for f, g, lo, hi, step, _ in plan:
        g = max(lo, min(hi, round(g / step) * step))
        k = g / 100.0
        out.append((f[0], g, round(f[1] * k, 1), round(f[2] * k, 1), round(f[3] * k, 1), round(f[4] * k, 1)))
    return out


def choose_template(meal_type, food_map, excluded, rng=random):
    """Случайное сочетание, где все продукты есть и не попадают под исключения."""
    ok = []
    for tpl in TEMPLATES[meal_type]:
        names = [n for n, s in tpl if s > 0]
        if all(n in food_map for n in names) and not any(tags(food_map[n]) & set(excluded) for n in names):
            ok.append(tpl)
    if ok:
        return rng.choice(ok)
    pick = lambda xs: [x for x in xs if x in food_map and not (tags(food_map[x]) & set(excluded))]
    prot, base, veg = pick(PLANT_PROTEIN), pick(PLANT_BASE), pick(PLANT_VEG)
    if meal_type == "snack":
        fruits = [f[0] for f in food_map.values() if f[5] == "fruit" and f[1] < 120]
        nuts = pick(sorted(NUTS))
        if fruits and nuts:
            return [(rng.choice(fruits), 0.5), (rng.choice(nuts), 0.5)]
    if prot and base and veg:
        return [(rng.choice(prot), 0.45), (rng.choice(base), 0.4), (rng.choice(veg), 0.15)]
    return None


def build_meal(meal_type, budget, food_map, excluded, rng=random):
    """Сочетание + граммы; если продукты упёрлись в границы, добирает калории гарниром."""
    tpl = choose_template(meal_type, food_map, excluded, rng)
    if not tpl:
        return []
    items = plan_meal(tpl, budget, food_map)
    for name in FILLERS[meal_type]:
        missing = budget - sum(i[2] for i in items)
        if missing <= max(60, budget * 0.08):
            break
        if name in food_map and name not in {i[0] for i in items} and not (tags(food_map[name]) & set(excluded)):
            items += plan_meal([(name, 1.0)], missing, food_map)
    return items
